-- Inventory movement history and business-defined low-stock thresholds.
CREATE TABLE IF NOT EXISTS inventory_settings (
 business_id BIGINT PRIMARY KEY REFERENCES businesses(id),
 low_stock_threshold INTEGER NOT NULL DEFAULT 20 CHECK (low_stock_threshold BETWEEN 0 AND 100000000)
);
CREATE TABLE IF NOT EXISTS stock_movements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 business_id BIGINT NOT NULL REFERENCES businesses(id),
 product_id BIGINT,
 product_name TEXT NOT NULL,
 quantity_change INTEGER NOT NULL,
 stock_before INTEGER NOT NULL,
 stock_after INTEGER NOT NULL,
 reason TEXT NOT NULL,
 source TEXT NOT NULL,
 reference_id BIGINT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_stock_movements_business_time ON stock_movements(business_id, created_at DESC, id DESC);
