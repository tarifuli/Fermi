-- Fermi preview: editable customer profiles, separate from immutable invoice history.
BEGIN;
CREATE TABLE IF NOT EXISTS customer_profiles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 business_id BIGINT NOT NULL REFERENCES businesses(id),
 customer_key TEXT NOT NULL,
 display_name TEXT NOT NULL,
 email TEXT NOT NULL DEFAULT '',
 phone TEXT NOT NULL DEFAULT '',
 notes TEXT NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE (business_id, customer_key)
);
CREATE INDEX IF NOT EXISTS idx_customer_profiles_business ON customer_profiles(business_id);
COMMIT;
