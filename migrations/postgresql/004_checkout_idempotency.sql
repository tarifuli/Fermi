-- Apply to the same PostgreSQL database used by the Fermi development preview.
-- Idempotent migration: safe to execute more than once.
CREATE TABLE IF NOT EXISTS checkout_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES businesses(id),
    request_key TEXT NOT NULL,
    payload_hash TEXT NOT NULL,
    invoice_id BIGINT REFERENCES invoices(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (business_id, request_key)
);
CREATE INDEX IF NOT EXISTS checkout_requests_created_at_idx
    ON checkout_requests (created_at);
