-- Build 09: invoice-linked, auditable customer returns.
CREATE TABLE IF NOT EXISTS sales_returns (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 business_id BIGINT NOT NULL REFERENCES businesses(id),
 invoice_id BIGINT NOT NULL REFERENCES invoices(id),
 request_key TEXT NOT NULL,
 request_hash TEXT NOT NULL,
 reason TEXT NOT NULL DEFAULT '',
 refund_amount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK(refund_amount>=0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 UNIQUE(business_id,request_key)
);
CREATE INDEX IF NOT EXISTS idx_sales_returns_business_date ON sales_returns(business_id,created_at DESC);
CREATE INDEX IF NOT EXISTS idx_sales_returns_invoice ON sales_returns(invoice_id);
CREATE TABLE IF NOT EXISTS sales_return_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 return_id BIGINT NOT NULL REFERENCES sales_returns(id),
 invoice_item_id BIGINT NOT NULL REFERENCES invoice_items(id),
 quantity INTEGER NOT NULL CHECK(quantity>0),
 restock BOOLEAN NOT NULL DEFAULT FALSE,
 UNIQUE(return_id,invoice_item_id)
);
