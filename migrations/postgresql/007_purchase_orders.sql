-- Purchase order management. No stock changes until receipt is recorded.
CREATE TABLE IF NOT EXISTS suppliers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 business_id BIGINT NOT NULL REFERENCES businesses(id),
 name TEXT NOT NULL,
 contact_name TEXT NOT NULL DEFAULT '',
 email TEXT NOT NULL DEFAULT '',
 phone TEXT NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 UNIQUE (id,business_id)
);
CREATE INDEX IF NOT EXISTS idx_suppliers_business ON suppliers(business_id,name);
CREATE TABLE IF NOT EXISTS purchase_orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 business_id BIGINT NOT NULL REFERENCES businesses(id),
 supplier_id BIGINT NOT NULL,
 status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','ordered','partially_received','received')),
 notes TEXT NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 ordered_at TIMESTAMPTZ,
 FOREIGN KEY (supplier_id,business_id) REFERENCES suppliers(id,business_id),
 UNIQUE (id,business_id)
);
CREATE INDEX IF NOT EXISTS idx_po_business ON purchase_orders(business_id,created_at DESC);
CREATE TABLE IF NOT EXISTS purchase_order_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 business_id BIGINT NOT NULL,
 purchase_order_id BIGINT NOT NULL,
 product_id BIGINT NOT NULL,
 quantity_ordered INTEGER NOT NULL CHECK (quantity_ordered BETWEEN 1 AND 100000),
 quantity_received INTEGER NOT NULL DEFAULT 0 CHECK (quantity_received >= 0 AND quantity_received <= quantity_ordered),
 unit_cost NUMERIC(14,2) NOT NULL CHECK (unit_cost >= 0),
 FOREIGN KEY (purchase_order_id,business_id) REFERENCES purchase_orders(id,business_id),
 UNIQUE (purchase_order_id,product_id)
);
CREATE TABLE IF NOT EXISTS purchase_order_receipts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 business_id BIGINT NOT NULL,
 purchase_order_id BIGINT NOT NULL,
 request_key TEXT NOT NULL,
 request_hash TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 FOREIGN KEY (purchase_order_id,business_id) REFERENCES purchase_orders(id,business_id),
 UNIQUE (business_id,request_key)
);
CREATE TABLE IF NOT EXISTS purchase_order_receipt_items (
 receipt_id BIGINT NOT NULL REFERENCES purchase_order_receipts(id),
 po_item_id BIGINT NOT NULL REFERENCES purchase_order_items(id),
 quantity INTEGER NOT NULL CHECK (quantity > 0),
 PRIMARY KEY (receipt_id,po_item_id)
);
